<?php

namespace App\Modules\Payments\Models;

use App\Modules\Doctors\Models\Doctor;
use App\Modules\Patients\Models\Patient;
use App\Modules\Payments\Enums\ChargeStatus;
use App\Modules\Queues\Models\QueueEntry;
use App\Modules\Staff\Models\User;
use Database\Factories\ChargeFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

/**
 * What one visit costs (data-model.md). Persistence mapping only; workflows live in ChargeService.
 * active_flag is generated by the database and never written. Its visit link is null only for a
 * cancelled charge whose check-in was undone (research R4).
 */
class Charge extends Model
{
    /** @use HasFactory<ChargeFactory> */
    use HasFactory;

    /**
     * @var list<string>
     */
    protected $fillable = [
        'queue_entry_id',
        'doctor_id',
        'patient_id',
        'date',
        'status',
        'fee',
        'discount',
        'amount_paid',
        'discount_reason',
        'discounted_by',
        'discounted_at',
        'charged_by',
        'cancel_reason',
        'cancelled_by',
        'cancelled_at',
    ];

    /**
     * @var array<string, mixed>
     */
    protected $attributes = [
        'discount' => '0.00',
        'amount_paid' => '0.00',
    ];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'date' => 'date',
            'status' => ChargeStatus::class,
            'fee' => 'decimal:2',
            'discount' => 'decimal:2',
            'amount_paid' => 'decimal:2',
            'discounted_at' => 'datetime',
            'cancelled_at' => 'datetime',
        ];
    }

    /**
     * @return BelongsTo<QueueEntry, $this>
     */
    public function queueEntry(): BelongsTo
    {
        return $this->belongsTo(QueueEntry::class);
    }

    /**
     * @return BelongsTo<Doctor, $this>
     */
    public function doctor(): BelongsTo
    {
        return $this->belongsTo(Doctor::class);
    }

    /**
     * @return BelongsTo<Patient, $this>
     */
    public function patient(): BelongsTo
    {
        return $this->belongsTo(Patient::class);
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function chargedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'charged_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function discountedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'discounted_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function cancelledBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'cancelled_by');
    }

    /**
     * @return HasMany<Payment, $this>
     */
    public function payments(): HasMany
    {
        return $this->hasMany(Payment::class)->orderBy('id');
    }

    /**
     * @return HasMany<Refund, $this>
     */
    public function refunds(): HasMany
    {
        return $this->hasMany(Refund::class)->orderBy('id');
    }

    protected static function newFactory(): ChargeFactory
    {
        return ChargeFactory::new();
    }
}
