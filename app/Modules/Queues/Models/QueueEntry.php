<?php

namespace App\Modules\Queues\Models;

use App\Modules\Appointments\Models\Appointment;
use App\Modules\Doctors\Models\Doctor;
use App\Modules\Patients\Models\Patient;
use App\Modules\Queues\Enums\QueueStatus;
use App\Modules\Staff\Models\User;
use Database\Factories\QueueEntryFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

/**
 * One patient in one doctor's waiting list for one clinic day (data-model.md). Persistence mapping
 * only; workflows live in QueueService and DoctorQueueService. with_doctor_flag is generated by the
 * database and never written.
 */
class QueueEntry extends Model
{
    /** @use HasFactory<QueueEntryFactory> */
    use HasFactory;

    /**
     * @var list<string>
     */
    protected $fillable = [
        'doctor_id',
        'patient_id',
        'appointment_id',
        'date',
        'queue_number',
        'order_minute',
        'status',
        'arrived_at',
        'checked_in_by',
        'called_at',
        'finished_at',
        'left_at',
        'left_by',
    ];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'date' => 'date',
            'queue_number' => 'integer',
            'order_minute' => 'integer',
            'status' => QueueStatus::class,
            'arrived_at' => 'datetime',
            'called_at' => 'datetime',
            'finished_at' => 'datetime',
            'left_at' => 'datetime',
        ];
    }

    /**
     * @return BelongsTo<Doctor, $this>
     */
    public function doctor(): BelongsTo
    {
        return $this->belongsTo(Doctor::class);
    }

    /**
     * @return BelongsTo<Patient, $this>
     */
    public function patient(): BelongsTo
    {
        return $this->belongsTo(Patient::class);
    }

    /**
     * @return BelongsTo<Appointment, $this>
     */
    public function appointment(): BelongsTo
    {
        return $this->belongsTo(Appointment::class);
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function checkedInBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'checked_in_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function leftBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'left_by');
    }

    protected static function newFactory(): QueueEntryFactory
    {
        return QueueEntryFactory::new();
    }
}
