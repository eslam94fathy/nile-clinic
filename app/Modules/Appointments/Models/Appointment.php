<?php

namespace App\Modules\Appointments\Models;

use App\Modules\Appointments\Enums\AppointmentStatus;
use App\Modules\Doctors\Models\Doctor;
use App\Modules\Patients\Models\Patient;
use App\Modules\Scheduling\Support\ClockTime;
use App\Modules\Staff\Models\User;
use Carbon\CarbonImmutable;
use Database\Factories\AppointmentFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

/**
 * A patient's appointment with a doctor (data-model.md). Persistence mapping only; workflows live
 * in BookingService and AppointmentService. scheduled_flag is generated by the database and never
 * written; outside_availability is a computed column selected by the repository (research R7).
 */
class Appointment extends Model
{
    /** @use HasFactory<AppointmentFactory> */
    use HasFactory;

    /**
     * @var list<string>
     */
    protected $fillable = [
        'patient_id',
        'doctor_id',
        'date',
        'start_minute',
        'end_minute',
        'status',
        'note',
        'booked_by',
        'rescheduled_by',
        'rescheduled_at',
        'status_changed_by',
        'status_changed_at',
        'cancellation_reason',
    ];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'date' => 'date',
            'start_minute' => 'integer',
            'end_minute' => 'integer',
            'status' => AppointmentStatus::class,
            'rescheduled_at' => 'datetime',
            'status_changed_at' => 'datetime',
            'outside_availability' => 'boolean',
        ];
    }

    /**
     * @return BelongsTo<Patient, $this>
     */
    public function patient(): BelongsTo
    {
        return $this->belongsTo(Patient::class);
    }

    /**
     * @return BelongsTo<Doctor, $this>
     */
    public function doctor(): BelongsTo
    {
        return $this->belongsTo(Doctor::class);
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function bookedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'booked_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function rescheduledBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'rescheduled_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function statusChangedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'status_changed_by');
    }

    /**
     * Started once its date and start time are at or before the clinic's wall-clock now (research
     * R5).
     */
    public function hasStarted(CarbonImmutable $now): bool
    {
        return $this->date->toDateString().' '.ClockTime::fromMinutes($this->start_minute) <= $now->format('Y-m-d H:i');
    }

    protected static function newFactory(): AppointmentFactory
    {
        return AppointmentFactory::new();
    }
}
